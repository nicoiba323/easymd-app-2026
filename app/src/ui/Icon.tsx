export type IconName = keyof typeof RAW;

const inner = (svg: string) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const PATHS = Object.fromEntries(Object.entries(RAW).map(([k, v]) => [k, inner(v)])) as Record<IconName, string>;

interface Props { name: IconName; size?: number; color?: string; style?: CSSProperties; className?: string }

export function Icon({ name, size = 20, color, style, className }: Props) {
  return (
    <svg viewBox="0 0 256 256" width={size} height={size} fill="currentColor" aria-hidden focusable="false" className={className}
      style={{ flexShrink: 0, color, ...style }} dangerouslySetInnerHTML={{ __html: PATHS[name] }} />
  );
}
